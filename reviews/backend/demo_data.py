def generate_demo_reviews(count: int = 160, seed: int = 20260807) -> list[dict]:
    rng = random.Random(seed)
    reviews: list[dict] = []
    for i in range(count):
        platform, product, rating, content = rng.choice(SEEDS)
        # 少量扰动，让数据不完全是重复模板
        if rng.random() < 0.15:
            rating = max(1, min(5, rating + rng.choice([-1, 1])))
        reviews.append({
            "id": f"demo-{i}",
            "content": content,
            "rating": rating,
            "date": f"2026-0{rng.randint(1, 7)}-{rng.randint(1, 28):02d}",
            "product": product,
            "platform": platform,
            "shop": "演示店铺",
        })
    return reviews
