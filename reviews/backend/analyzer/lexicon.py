# 否定词（翻转最近一个情感词极性）
NEGATORS = {"不", "没", "没有", "别", "无", "未", "勿", "不太", "不怎么", "并非", "毫无"}

# 程度副词（放大/缩小情感权重）
DEGREE = {"非常": 1.6, "特别": 1.6, "超级": 1.6, "极其": 1.8, "太": 1.5, "很": 1.4,
          "十分": 1.5, "真的": 1.3, "真心": 1.3, "简直": 1.6, "彻底": 1.5,
          "有点": 0.6, "稍微": 0.6, "略显": 0.6, "一般": 0.5}

THRESHOLD = 0.15  # |score| 高于此判定为正向/负向


class LexiconAnalyzer:
    name = "lexicon"

    def __init__(self) -> None:
        # 预加载词典：把含词直接加入 jieba 词典，避免把「物美价廉」拆散
        for word in list(POSITIVE_WORDS) + list(NEGATIVE_WORDS):
            jieba.add_word(word)

    def analyze(self, text: str) -> ReviewResult:
        tokens = [t.strip() for t in jieba.lcut(text) if t.strip()]
        score = 0.0
        hits = 0
        for i, tok in enumerate(tokens):
            weight = POSITIVE_WORDS.get(tok) or NEGATIVE_WORDS.get(tok)
            if weight is None:
                continue
            hits += 1
            sign = 1.0 if tok in POSITIVE_WORDS else -1.0
            # 否定词：向前最多看 2 个 token
            for j in range(max(0, i - 2), i):
                if tokens[j] in NEGATORS:
                    sign *= -1.0
                    break
            # 程度副词：向前看 1 个 token
            if i > 0 and tokens[i - 1] in DEGREE:
                weight *= DEGREE[tokens[i - 1]]
            score += sign * weight

        if hits == 0:
            sentiment = "neutral"
            confidence = 0.3
        else:
            score = max(-3.0, min(3.0, score))
            sentiment = "positive" if score > THRESHOLD else ("negative" if score < -THRESHOLD else "neutral")
            confidence = min(1.0, 0.5 + min(0.5, abs(score) / 3.0))

        return ReviewResult(
            sentiment=sentiment,
            score=round(0.5 + score / 6.0, 4),  # 映射到 0-1，0.5 为中性
            confidence=round(confidence, 4),
            source="lexicon",
        )
